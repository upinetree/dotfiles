# report-session の trigger hook が source する。区切りの候補でモデルに渡す注入文を作る。
#
# hook は区切りの「候補」を文字列で拾うだけで、本当に区切りか・学びがあるかの判断は会話全体を
# 持つモデルに任せる。両方を満たせば、ユーザーに確認せず起動させる。
#
# 2026-11 までは、次の場合に提案に留めていた（ユーザーの承認を待つ）。どれも外してある:
#   - コンテキスト残量が 50% 未満。report-session は会話履歴を継承する fork で動くので、
#     残量が少ないと fork が上限に届く、という理由だった。実測すると fork が足す量は小さく
#     （レポートを書いた fork の記録 78 件で、中央値 2.8 万、最大 8 万トークン。使用量が
#     79 万〜90 万トークンの状態から始まった 4 件も compaction なしで書き終えている）、
#     提案に留めても危険は減らなかった（承認されれば、同じ fork が同じ残量から走る）
#   - Codex。履歴を継承するサブエージェントが無く、本体のコンテキストを使うと考えていたが、
#     Codex Desktop は履歴を引き継ぐサブエージェントでレポートを書けていた（2026-11 の記録。
#     spawn_agent の fork_turns を省いた呼び出し）
#   - このセッションで起動済み。2 回目以降の起動で更新か分割かをユーザーに聞くかどうかは
#     skill が決めることで、hook が先回りして止めると skill 側の決め方を変えても効かなくなる

# 起動済みのセッションでも起動させるので、観点 2 を前回の起動より後の分に限らないと、
# 区切りの候補が来るたびに同じ内容で起動することになる。
# 1 行目の「/ 自動実行」は、提案に留める注入文（[report-session 自動トリガー]）があった頃の
# 名残で、過去の transcript と同じ見出しで数えられるよう残してある。
# $1: 区切りの候補の説明 / $2: 本当に区切りかを確かめる観点
report_session_context() {
  cat <<EOF
[report-session 自動トリガー / 自動実行]
$1
次の 2 点を自分で評価せよ。

1. 本当に作業の区切りか。$2作業がまだ続く見込みなら区切りではない（後の区切りに回す）。
2. このセッションに「後から参照する価値のある学び・調査結果・設計判断」が蓄積されているか。このセッションで report-session を起動済みなら、前回の起動より後に蓄積された分だけで判断する。

- 両方を満たす場合は、ユーザーに確認せず report-session skill を起動する（Claude Code では Skill ツールを使う）。ユーザーは、この自動実行を hook の設定で許可済みである。応答の最後に、バックグラウンドでレポートを作成中である旨を一行添える。
- どちらかを満たさなければ、起動しない（何もしない。この判断に触れる必要もない）。
EOF
}

# 引数: hookEventName / 区切りの候補の説明 / 確かめる観点
report_session_emit() {
  jq -nc --arg event "$1" --arg ctx "$(report_session_context "$2" "$3")" \
    '{hookSpecificOutput: {hookEventName: $event, additionalContext: $ctx}}'
}
